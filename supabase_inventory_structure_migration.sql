-- Upgrade an existing Brewora database from the earlier UUID/pack-based
-- inventory shape to the requested inventory_id/name/quantity/unit shape.
-- Preserves existing recipe and movement links, quantities, and order history.
-- Demo balances are applied only to existing zero-quantity rows; replace these
-- sample counts with a physical stock count before real operation.

begin;

-- Remove old name-sync triggers before changing the inventory columns.
drop trigger if exists menu_ingredients_sync_names on public.menu_ingredients;
drop trigger if exists menu_item_sync_recipe_names on public.menu_items;
drop trigger if exists inventory_sync_recipe_names on public.inventory;
drop function if exists public.sync_menu_ingredient_names();
drop function if exists public.sync_menu_ingredient_menu_name();
drop function if exists public.sync_menu_ingredient_inventory_name();

-- Add the new integer key when upgrading from the original UUID shape.
alter table public.inventory
  add column if not exists inventory_id integer generated by default as identity;
create unique index if not exists inventory_inventory_id_upgrade_key
  on public.inventory(inventory_id);

-- If the old UUID column is still present, map recipe and movement references.
-- If a prior attempt already removed it, keep the existing integer references.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'inventory' and column_name = 'id') then
    alter table public.menu_ingredients add column if not exists inventory_id_new integer;
    update public.menu_ingredients mi
      set inventory_id_new = i.inventory_id
      from public.inventory i
      where i.id = mi.inventory_id and mi.inventory_id_new is null;
    alter table public.menu_ingredients drop constraint if exists menu_ingredients_inventory_id_fkey;
    alter table public.menu_ingredients drop constraint if exists menu_ingredients_menu_item_id_inventory_id_key;
    alter table public.menu_ingredients drop column inventory_id;
    alter table public.menu_ingredients rename column inventory_id_new to inventory_id;
    alter table public.menu_ingredients alter column inventory_id set not null;
    alter table public.menu_ingredients
      add constraint menu_ingredients_inventory_id_fkey
      foreign key (inventory_id) references public.inventory(inventory_id) on delete restrict;
    alter table public.menu_ingredients
      add constraint menu_ingredients_menu_item_id_inventory_id_key unique (menu_item_id, inventory_id);

    alter table public.inventory_movements add column if not exists inventory_id_new integer;
    update public.inventory_movements im
      set inventory_id_new = i.inventory_id
      from public.inventory i
      where i.id = im.inventory_id and im.inventory_id_new is null;
    drop index if exists public.inventory_movements_inventory_created_idx;
    alter table public.inventory_movements drop constraint if exists inventory_movements_inventory_id_fkey;
    alter table public.inventory_movements drop column inventory_id;
    alter table public.inventory_movements rename column inventory_id_new to inventory_id;
    alter table public.inventory_movements alter column inventory_id set not null;
    alter table public.inventory_movements
      add constraint inventory_movements_inventory_id_fkey
      foreign key (inventory_id) references public.inventory(inventory_id) on delete restrict;
    create index inventory_movements_inventory_created_idx
      on public.inventory_movements(inventory_id, created_at desc);

    alter table public.inventory drop constraint if exists inventory_pkey;
    alter table public.inventory drop column id;
    alter table public.inventory add constraint inventory_pkey primary key (inventory_id);
  else
    -- A failed earlier run may have left empty temporary columns behind.
    alter table public.menu_ingredients drop column if exists inventory_id_new;
    alter table public.inventory_movements drop column if exists inventory_id_new;
    if not exists (
      select 1 from pg_constraint
      where conrelid = 'public.inventory'::regclass and contype = 'p'
    ) then
      alter table public.inventory add constraint inventory_pkey primary key (inventory_id);
    end if;
  end if;
end $$;

-- Keep inventory_inventory_id_upgrade_key if the new foreign keys use it. It
-- is redundant with the primary key but safe and avoids breaking those links.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'inventory' and column_name = 'name') then
    alter table public.inventory rename column name to ingredient_name;
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'inventory' and column_name = 'base_unit') then
    alter table public.inventory rename column base_unit to unit;
  end if;
end $$;
alter table public.inventory drop column if exists purchase_unit;
alter table public.inventory drop column if exists quantity_per_pack;
alter table public.inventory drop column if exists created_at;
alter table public.inventory alter column ingredient_name type varchar(100);
alter table public.inventory alter column unit type varchar(20);
alter table public.inventory alter column quantity type numeric(10,3);
alter table public.inventory alter column reorder_level type numeric(10,3);
alter table public.inventory alter column unit set not null;

-- Remove old RPC signatures; the updated setup script below recreates the
-- matching functions for the simplified units and integer inventory IDs.
drop function if exists public.create_inventory_ingredient(text, text, text, numeric, numeric, numeric);
drop function if exists public.receive_inventory_stock(uuid, numeric);

-- Sample opening counts from the updated setup seed. Existing nonzero stock is
-- preserved; zero balances receive demo values so the sample recipes can be tried.
with demo(ingredient_name, quantity, reorder_level) as (values
  ('Coffee Beans', 5000::numeric, 500::numeric), ('Milk', 10000, 2000), ('Water', 20000, 3000), ('Ice', 10000, 2000),
  ('Chocolate Syrup', 1000, 200), ('Caramel Syrup', 1000, 200), ('Vanilla Syrup', 1000, 200),
  ('White Chocolate Syrup', 1000, 200), ('Frappe Powder', 3000, 500), ('Whipped Cream', 1000, 200),
  ('Black Tea', 500, 100), ('Earl Grey Tea', 500, 100), ('Matcha Powder', 500, 100), ('Lemon Juice', 1000, 200),
  ('Sugar', 3000, 500), ('Sugar Syrup', 1000, 200), ('Chocolate Powder', 1000, 200),
  ('White Chocolate', 1000, 200), ('Chocolate Chips', 1000, 200), ('All-Purpose Flour', 5000, 1000),
  ('Butter', 2000, 500), ('Yeast', 500, 100), ('Salt', 1000, 200), ('Blueberries', 1000, 200),
  ('Eggs', 120, 24), ('Baking Powder', 500, 100), ('Cocoa Powder', 1000, 200),
  ('Baking Soda', 500, 100), ('Chocolate', 2000, 500)
), changed as (
  update public.inventory i
  set quantity = d.quantity, reorder_level = d.reorder_level, updated_at = now()
  from demo d
  where i.ingredient_name = d.ingredient_name and i.quantity = 0
  returning i.inventory_id, i.ingredient_name, i.quantity, i.unit
)
insert into public.inventory_movements(inventory_id, movement_type, quantity_change, note)
select inventory_id, 'initial_stock', quantity,
  format('Demo opening balance for school project: %s %s; replace with counted stock', quantity, unit)
from changed;

notify pgrst, 'reload schema';

-- After this migration succeeds, run the updated supabase_inventory_setup.sql
-- to recreate the order deduction functions and seed any missing recipes.
select inventory_id, ingredient_name, quantity, unit, reorder_level, updated_at
from public.inventory
order by inventory_id;

commit;
