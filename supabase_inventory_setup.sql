create or replace function public.add_inventory_ingredient(
  p_ingredient_name text,
  p_unit text,
  p_purchase_unit text,
  p_base_quantity_per_purchase numeric,
  p_initial_purchases numeric,
  p_reorder_level numeric
)
returns integer language plpgsql security definer set search_path = ''
as $$
declare
  v_inventory_id integer;
  v_quantity numeric(10,3);
begin
  if not (select public.is_inventory_admin()) then raise exception 'Only admins can add inventory ingredients.'; end if;
  if nullif(btrim(p_ingredient_name), '') is null or nullif(btrim(p_unit), '') is null or nullif(btrim(p_purchase_unit), '') is null then
    raise exception 'Ingredient name and units are required.';
  end if;
  if p_base_quantity_per_purchase is null or p_base_quantity_per_purchase <= 0 or p_initial_purchases is null or p_initial_purchases < 0 or p_reorder_level is null or p_reorder_level < 0 then
    raise exception 'Pack conversion, opening quantity, and reorder level must be valid non-negative values.';
  end if;
  v_quantity := p_base_quantity_per_purchase * p_initial_purchases;
  insert into public.inventory(ingredient_name, unit, quantity, reorder_level, status)
  values (
    btrim(p_ingredient_name), btrim(p_unit), v_quantity, p_reorder_level,
    case when v_quantity <= p_reorder_level then 'low_stock' else 'available' end
  )
  returning inventory_id into v_inventory_id;
  insert into public.inventory_purchase_conversions(inventory_id, purchase_unit, base_quantity_per_purchase)
  values (v_inventory_id, btrim(p_purchase_unit), p_base_quantity_per_purchase);
  if v_quantity > 0 then
    insert into public.inventory_movements(inventory_id, movement_type, quantity_change, note, actor_id)
    values (v_inventory_id, 'initial_stock', v_quantity, format('Initial stock: %s %s × %s %s', p_initial_purchases, p_purchase_unit, p_base_quantity_per_purchase, p_unit), (select auth.uid()));
  end if;
  return v_inventory_id;
end;
$$;

drop function if exists public.receive_inventory_stock(integer, numeric);
create function public.receive_inventory_stock(p_inventory_id integer, p_quantity numeric)
returns numeric language plpgsql security definer set search_path = ''
as $$
declare
  v_new_quantity numeric(12,3);
begin
  if not (select public.is_inventory_admin()) then raise exception 'Only admins can receive stock.'; end if;
  if p_quantity is null or p_quantity <= 0 then raise exception 'Enter a quantity greater than zero.'; end if;
  perform 1 from public.inventory where inventory_id = p_inventory_id for update;
  if not found then raise exception 'Ingredient not found.'; end if;
  update public.inventory
  set quantity = quantity + p_quantity,
      status = case
        -- Preserve an explicit unavailable flag; receiving stock alone should
        -- not re-enable an ingredient an admin intentionally disabled.
        when status = 'unavailable' then 'unavailable'
        when quantity + p_quantity <= reorder_level then 'low_stock'
        else 'available'
      end
  where inventory_id = p_inventory_id
  returning quantity into v_new_quantity;
  insert into public.inventory_movements(inventory_id, movement_type, quantity_change, note, actor_id)
  values (p_inventory_id, 'stock_in', p_quantity, format('%s %s received', p_quantity, (select unit from public.inventory where inventory_id = p_inventory_id)), (select auth.uid()));
  return v_new_quantity;
end;
$$;

