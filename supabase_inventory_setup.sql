-- Keep the readable labels aligned with the referenced records on writes/renames.
create or replace function public.sync_menu_ingredient_names()
returns trigger language plpgsql set search_path = ''
as $$
begin
  select m.name into new.menu_name from public.menu_items m where m.id = new.menu_item_id;
  select i.ingredient_name into new.ingredient_name from public.inventory i where i.inventory_id = new.inventory_id;
  select i.unit into new.unit from public.inventory i where i.inventory_id = new.inventory_id;
  if new.menu_name is null or new.ingredient_name is null or new.unit is null then
    raise exception 'Menu item and inventory ingredient must exist.';
  end if;
  return new;
end;
$$;

drop trigger if exists menu_ingredients_sync_names on public.menu_ingredients;
create trigger menu_ingredients_sync_names before insert or update of menu_item_id, inventory_id
  on public.menu_ingredients for each row execute function public.sync_menu_ingredient_names();

