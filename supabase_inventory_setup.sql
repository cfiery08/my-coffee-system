create policy "Cashiers delete own empty POS orders" on public.orders
  for delete to authenticated using (
    user_id is null and cashier_id = (select auth.uid())
    and (select public.is_inventory_pos_user())
    and (select public.order_has_no_items(orders.id))
  );
