-- Brewora inventory, recipes, stock movements, and order deductions.
-- Fresh database: run this file in Supabase SQL Editor.
-- Existing pack-based inventory: first run supabase_inventory_structure_migration.sql,
-- then run this file to recreate functions and seed missing recipes.
-- The supplied opening quantities are demo balances for the school project;
-- replace them with a physical count before using real orders.
-- Recipe links are matched by menu item names (with common aliases); review
-- the final query for any menu items that still need a recipe.

create table if not exists public.inventory (
  inventory_id integer generated by default as identity primary key,
  ingredient_name varchar(100) not null unique,
  quantity numeric(10,3) not null default 0 check (quantity >= 0),
  unit varchar(20) not null,
  reorder_level numeric(10,3) not null default 0 check (reorder_level >= 0),
  status text not null default 'available' check (status in ('available', 'unavailable', 'low_stock')),
  updated_at timestamptz not null default now()
);

alter table public.inventory add column if not exists status text not null default 'available';
alter table public.inventory drop constraint if exists inventory_status_check;
alter table public.inventory add constraint inventory_status_check check (status in ('available', 'unavailable', 'low_stock'));

-- Purchase packaging is stored separately so inventory keeps the requested
-- ingredient_name/quantity/unit/reorder_level structure.
create table if not exists public.inventory_purchase_conversions (
  inventory_id integer primary key references public.inventory(inventory_id) on delete cascade,
  purchase_unit text not null,
  base_quantity_per_purchase numeric(10,3) not null check (base_quantity_per_purchase > 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.menu_ingredients (
  id uuid primary key default gen_random_uuid(),
  menu_item_id uuid not null references public.menu_items(id) on delete cascade,
  inventory_id integer not null references public.inventory(inventory_id) on delete cascade,
  menu_name text not null,
  ingredient_name text not null,
  unit varchar(20) not null,
  quantity_required numeric(12,3) not null check (quantity_required > 0),
  created_at timestamptz not null default now(),
  unique (menu_item_id, inventory_id)
);

-- Migrate an existing table from the earlier setup and populate readable labels.
