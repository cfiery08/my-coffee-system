-- One order item consumes its per-item recipe quantity multiplied by the ordered quantity.
create or replace function public.deduct_order_item_ingredients()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  v_recipe record;
  v_needed numeric(12,3);
  v_available numeric(12,3);
begin
  if new.menu_item_id is null then raise exception 'Cannot deduct stock: menu item is missing from this order item.'; end if;
  if not exists (select 1 from public.menu_ingredients where menu_item_id = new.menu_item_id) then
    raise exception 'Cannot place order: no ingredient recipe is configured for "%".', new.menu_item_name;
  end if;
  for v_recipe in
    select mi.inventory_id, mi.quantity_required, i.ingredient_name as name, i.unit
    from public.menu_ingredients mi
    join public.inventory i on i.inventory_id = mi.inventory_id
    where mi.menu_item_id = new.menu_item_id
    order by mi.inventory_id
  loop
    v_needed := v_recipe.quantity_required * new.quantity;
    update public.inventory
      set quantity = quantity - v_needed
      where inventory_id = v_recipe.inventory_id and quantity >= v_needed
      returning quantity into v_available;
    if not found then
      select quantity into v_available from public.inventory where inventory_id = v_recipe.inventory_id;
      raise exception 'Not enough % in stock. Need % %, have % %.', v_recipe.name, v_needed,
        v_recipe.unit, coalesce(v_available, 0), v_recipe.unit;
    end if;
    insert into public.inventory_movements(inventory_id, order_id, order_item_id, movement_type, quantity_change, note, actor_id)
    values (v_recipe.inventory_id, new.order_id, new.id, 'order_consumption', -v_needed,
      format('%s × %s', new.quantity, new.menu_item_name), (select auth.uid()));
  end loop;
  return new;
end;
$$;

drop trigger if exists order_item_deduct_ingredients on public.order_items;
create trigger order_item_deduct_ingredients after insert on public.order_items
  for each row execute function public.deduct_order_item_ingredients();

-- Return consumed stock exactly once when an order is cancelled.
create or replace function public.return_cancelled_order_ingredients()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  v_item record;
begin
  if new.status = 'cancelled' and old.status is distinct from 'cancelled' then
    for v_item in
      select oi.id as order_item_id, 1 as quantity, oi.menu_item_name,
        m.inventory_id, i.ingredient_name, -m.quantity_change as quantity_required, i.unit
      from public.inventory_movements m
      join public.order_items oi on oi.id = m.order_item_id
      join public.inventory i on i.inventory_id = m.inventory_id
      where m.order_id = new.id and m.movement_type = 'order_consumption'
        and not exists (select 1 from public.inventory_movements returned
          where returned.order_item_id = oi.id and returned.inventory_id = m.inventory_id
            and returned.movement_type = 'order_cancellation_return')
      order by m.inventory_id, oi.id
    loop
      update public.inventory set quantity = quantity + (v_item.quantity_required * v_item.quantity)
        where inventory_id = v_item.inventory_id;
      insert into public.inventory_movements(inventory_id, order_id, order_item_id, movement_type, quantity_change, note, actor_id)
      values (v_item.inventory_id, new.id, v_item.order_item_id, 'order_cancellation_return',
        v_item.quantity_required * v_item.quantity, format('Cancelled order item: %s', v_item.menu_item_name), (select auth.uid()));
    end loop;
  end if;
  return new;
end;
$$;

drop trigger if exists order_cancel_return_ingredients on public.orders;
create trigger order_cancel_return_ingredients after update of status on public.orders
  for each row execute function public.return_cancelled_order_ingredients();

-- The app removes an empty order header when its order-item insert fails (for example, low stock).
create or replace function public.order_has_no_items(p_order_id uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.orders o
    where o.id = p_order_id
      and (
        (o.user_id = (select auth.uid()) and o.status = 'pending')
        or (o.user_id is null and o.cashier_id = (select auth.uid()) and exists (
          select 1 from public.user_accounts ua
          where ua.id = (select auth.uid()) and ua.role in ('cashier', 'admin')
        ))
      )
      and not exists (select 1 from public.order_items oi where oi.order_id = p_order_id)
  );
$$;
revoke all on function public.order_has_no_items(uuid) from public, anon;
grant execute on function public.order_has_no_items(uuid) to authenticated;

drop policy if exists "Customers delete empty pending orders" on public.orders;
create policy "Customers delete empty pending orders" on public.orders
  for delete to authenticated using (
    user_id = (select auth.uid()) and status = 'pending'
    and (select public.order_has_no_items(orders.id))
  );
